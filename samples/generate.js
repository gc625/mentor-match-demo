'use strict';
// Recreate the synthetic CSV examples deterministically with `node samples/generate.js`.
const fs = require('node:fs');
const path = require('node:path');

const first = ['Amira','Daniel','Elena','Marcus','Nadia','Theo','Sofia','Julian','Maya','Noah','Priya','Leah','Aisha','Benjamin','Chloe','David','Emily','Farah','Gabriel','Hannah','Isaac','Jasmine','Kai','Lina','Mateo','Nora','Omar','Paige','Quinn','Ravi','Sara','Tariq','Uma','Victor','Winnie','Xavier','Yara','Zachary','Ada','Brandon','Clara','Darius','Esther','Felix','Grace','Hugo','Iris','Jonah','Keira','Luca','Miriam','Nikhil','Olivia','Peter','Rosa','Samuel','Tessa','Uchenna','Valeria','William'];
const last = ['Patel','Brooks','Rossi','Lee','Okafor','Bennett','Reyes','Park','Chen','Kim','Shah','Morgan','Ahmed','Carter','Nguyen','Rivera','Wilson','Hassan','Silva','Taylor','Cohen','Singh','Tanaka','Haddad','Garcia','Murphy','Ali','Turner','Reed','Mehta','Khan','Jones','Iyer','Dubois','Zhang','Miller','Hussein','Young','Mensah','Davis','Cooper','Jackson','Abebe','Martin','Wright','Lopez','Anderson','Green','Olsen','Russo','Levy','Gupta','Brown','Evans','Costa','Walker','Scott','Eze','Torres','Clark'];
const mentors = first.map((name, i) => `${name} ${last[i]}`);
const mentees = first.map((name, i) => `${name} ${last[(i + 31) % last.length]}`);
let seed = 84329;
function random() { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed / 2 ** 32; }
function shuffle(items) {
  const result = items.slice();
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
const mentorGroups = shuffle(mentors);
const menteeGroups = shuffle(mentees);
const mentorChoices = new Map(mentors.map(name => [name, []]));
const menteeChoices = new Map(mentees.map(name => [name, []]));
// Four mutual choices per person in small cohorts create competing preferences.
// One extra, cross-cohort choice may be one-sided, exercising eligibility.
for (let g = 0; g < 6; g++) {
  for (let i = 0; i < 10; i++) {
    for (const offset of [0, 1, 3, 7]) {
      const mentor = mentorGroups[g * 10 + i];
      const mentee = menteeGroups[g * 10 + (i + offset) % 10];
      mentorChoices.get(mentor).push(mentee);
      menteeChoices.get(mentee).push(mentor);
    }
    const otherGroup = (g + 1 + Math.floor(random() * 5)) % 6;
    mentorChoices.get(mentorGroups[g * 10 + i]).push(menteeGroups[otherGroup * 10 + Math.floor(random() * 10)]);
    menteeChoices.get(menteeGroups[g * 10 + i]).push(mentorGroups[otherGroup * 10 + Math.floor(random() * 10)]);
  }
}
function csv(people, choices) {
  return 'Name,Preferences\n' + people.map(name => `${name},"${shuffle(choices.get(name)).join(', ')}"`).join('\n') + '\n';
}
const mentorsCSV = csv(mentors, mentorChoices);
const menteesCSV = csv(mentees, menteeChoices);
fs.writeFileSync(path.join(__dirname, 'mentors.csv'), mentorsCSV);
fs.writeFileSync(path.join(__dirname, 'mentees.csv'), menteesCSV);
// Inline data works in a browser even when index.html is opened as a local file.
const source = `/* Generated by samples/generate.js; edit the generator instead. */\n` +
  `(function (root) {\n  const sample = ${JSON.stringify({mentorsCSV, menteesCSV}, null, 2)};\n` +
  `  if (typeof module === 'object' && module.exports) module.exports = sample;\n` +
  `  else root.MentorMatchSample = sample;\n})(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
fs.writeFileSync(path.join(__dirname, '..', 'sample.js'), source);
